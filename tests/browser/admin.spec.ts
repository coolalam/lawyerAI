import { test, expect } from '@playwright/test'

test('manage departments, members, accounts and metadata', async ({ page }) => {
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const bootstrap=await (await page.request.get('/api/bootstrap')).json()
  if(bootstrap.setup_required)await page.request.post('/api/setup',{data:{username:'admin',name:'林知远',password:'Browser-test-2026',demo:true}})
  await page.goto('/')
  await page.getByLabel('账号',{exact:true}).fill('admin')
  await page.getByLabel('密码',{exact:true}).fill('Browser-test-2026')
  await page.getByRole('button',{name:'登录工作空间'}).click()
  await page.getByRole('button',{name:'管理后台',exact:true}).click()
  await page.getByRole('button',{name:'部门与成员',exact:true}).click()
  await page.getByRole('button',{name:'新增部门',exact:true}).click()
  const organization=page.locator('#organization-editor')
  await organization.getByLabel('分所',{exact:false}).fill('上海测试分所')
  await organization.getByLabel('部门编码').fill('E2E-DEPT')
  await organization.getByLabel('部门名称').fill('测试业务部')
  await organization.getByRole('button',{name:'保存部门'}).click()
  await expect(organization).not.toBeVisible()
  await expect(page.locator('.team-tree-node.department').filter({hasText:'E2E-DEPT'})).toContainText('测试业务部')
  await page.locator('.team-tree-node.department').filter({hasText:'E2E-DEPT'}).click()
  await page.getByRole('button',{name:'编辑部门',exact:true}).click()
  await expect(organization.getByLabel('部门名称')).toHaveValue('测试业务部')
  await organization.getByRole('button',{name:'关闭编辑',exact:true}).click()
  await page.getByRole('button',{name:'新增成员',exact:true}).click()
  await organization.getByLabel('姓名',{exact:false}).fill('管理浏览器成员')
  const department=organization.getByRole('combobox',{name:'部门',exact:true})
  const departmentId=await department.getByRole('option',{name:/E2E-DEPT/}).getAttribute('value')
  await department.selectOption(departmentId!)
  await organization.getByRole('button',{name:'保存成员',exact:true}).click()
  await expect(organization).not.toBeVisible()
  await page.getByLabel('搜索部门或成员').fill('管理浏览器成员')
  await expect(page.locator('.lawyer-team-members tbody tr')).toHaveCount(1)
  await page.locator('.lawyer-team-members tbody tr').getByRole('button',{name:'编辑',exact:true}).click()
  await organization.getByLabel('登录账号',{exact:false}).fill('browser-managed-member')
  await organization.getByRole('button',{name:'创建登录账号',exact:true}).click()
  await expect(organization.getByRole('heading',{name:'密码重置申请'})).toBeVisible()
  await organization.getByRole('button',{name:'关闭编辑',exact:true}).click()
  await expect(page.locator('.lawyer-team-members tbody tr')).toContainText('待设置密码')
  await page.getByRole('button',{name:'元数据管理',exact:true}).click()
  await page.getByRole('button',{name:'新增字典项'}).click()
  const metadata=page.locator('#metadata-editor')
  await metadata.getByLabel('类别',{exact:false}).fill('case_cause')
  await metadata.getByLabel('编码 *',{exact:true}).fill('E2E-CAUSE')
  await metadata.getByLabel('显示名称').fill('测试合同争议')
  await metadata.getByRole('button',{name:'保存字典项'}).click()
  await expect(metadata).not.toBeVisible()
  await page.getByLabel('搜索字典项').fill('E2E-CAUSE')
  await expect(page.locator('.metadata-tree-node')).toHaveCount(1)
  await page.locator('.metadata-tree-node').getByRole('button',{name:'编辑'}).click()
  await expect(metadata.getByLabel('编码 *',{exact:true})).toBeDisabled()
  await metadata.getByLabel('显示名称').fill('测试合同纠纷')
  await metadata.getByLabel('启用',{exact:true}).uncheck()
  await metadata.getByRole('button',{name:'保存字典项'}).click()
  await expect(metadata).not.toBeVisible()
  await expect(page.locator('.metadata-tree-node')).toContainText('测试合同纠纷')
  await expect(page.locator('.metadata-tree-node')).toContainText('停用')
  await page.getByRole('button',{name:'API Key 管理',exact:true}).click()
  await expect(page.getByRole('heading',{name:'API Key 管理',exact:true})).toBeVisible()
  await page.getByLabel('Key 名称 *').fill('浏览器案件查询')
  await page.getByRole('button',{name:'创建 API Key',exact:true}).click()
  await expect(page.getByText('API Key 已创建，请立即复制保存')).toBeVisible()
  await expect(page.locator('.api-key-value code')).toContainText('law_mcp_')
  await page.getByRole('button',{name:'复制 Key',exact:true}).click()
  await expect(page.getByRole('button',{name:'已复制',exact:true})).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  await expect(page.locator('.api-key-panel')).toContainText('已撤销')
  await page.screenshot({path:'artifacts/screenshots/admin-metadata.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
