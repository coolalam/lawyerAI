test('forgot password requires administrator verification and a single-use code',async({page,request})=>{
  await request.post('/api/auth/login',{data:{username:'admin',password:'Browser-test-2026'}})
  const created=await request.post('/api/admin/users',{data:{username:'recovery-e2e',name:'重置测试成员',role:'clerk',password:'Original-password-2026'}})
  expect(created.ok()).toBeTruthy()
  const member=await created.json()
  await page.goto('/')
  await page.getByRole('button',{name:'忘记密码 / 首次设置密码',exact:true}).click()
  await page.getByLabel('登录账号',{exact:true}).fill('recovery-e2e')
  await page.getByRole('button',{name:'提交重置申请',exact:true}).click()
  await expect(page.getByText('如账号存在且已启用，重置申请已提交。',{exact:false})).toBeVisible()
  const requests=await (await request.get('/api/admin/password-reset-requests')).json()
  expect(requests.some((r:any)=>r.user_id===member.id)).toBeTruthy()
  const issued=await request.post(`/api/admin/users/${member.id}/password-reset-token`,{data:{verification_note:'浏览器测试已核验本人身份'}})
  const token=(await issued.json()).token
  await page.getByRole('button',{name:'已有重置码',exact:true}).click()
  await page.getByLabel('一次性重置码',{exact:true}).fill(token)
  await page.getByLabel('新密码',{exact:true}).fill('Recovered-password-2026')
  await page.getByLabel('确认新密码',{exact:true}).fill('Recovered-password-2026')
  await page.getByRole('button',{name:'设置新密码',exact:true}).click()
  await expect(page.getByText('密码已设置，请返回登录。',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'返回登录',exact:true}).click()
  await page.getByLabel('账号',{exact:true}).fill('recovery-e2e')
  await page.getByLabel('密码',{exact:true}).fill('Recovered-password-2026')
  await page.getByRole('button',{name:'登录工作空间'}).click()
  await expect(page.getByRole('heading',{name:'重置测试成员，工作顺利'})).toBeVisible()
  const repeated=await request.post('/api/auth/reset-password',{data:{token,password:'Another-password-2026'}})
  expect(repeated.status()).toBe(422)
})

